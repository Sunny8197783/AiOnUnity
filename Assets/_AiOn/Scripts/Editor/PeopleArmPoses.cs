using System.Collections.Generic;
using System.IO;
using System.Text;
using AiOn.People;
using UnityEditor;
using UnityEngine;

namespace AiOn.EditorTools
{
    /// <summary>
    /// The arm poses of the people's "Arms" layer (PersonClips.ArmPoses): small static Humanoid clips of both arms and
    /// the fingers (Art/People/Rocketbox/Anim/arms_&lt;pose&gt;.anim) under one avatar mask (arms.mask). Muscle space is
    /// normalised, so one clip serves every avatar. Each pose is solved, not hand-keyed: on 정민's prefab in the base
    /// state the pose goes with (idle for the cart, the floor sit for the others), the arm muscles are searched until the
    /// palm grips reach their targets with the palms facing down:
    /// <list type="bullet">
    /// <item>cart: both palms on the handle bar (<see cref="PersonProps.CartHandle"/>, 0.21 m either side);</item>
    /// <item>sitKnees: palms resting on the thighs, three quarters of the way to the knees;</item>
    /// <item>sitBack: palms flat on the floor a little behind and outside the hips, leaning back on straight arms.</item>
    /// </list>
    /// Regenerated by AiOn → Build People (before the controllers); AiOn → People → Solve Arm Poses alone writes a report.
    /// </summary>
    public static class PeopleArmPoses
    {
        public static string MaskPath => PersonClips.AnimFolder + "/arms.mask";
        public static string PosePath(string pose) => $"{PersonClips.AnimFolder}/arms_{pose}.anim";

        const int FirstArmMuscle = 37, ArmMuscles = 18, FirstFinger = 55, Fingers = 40; // HumanTrait muscle order

        [MenuItem("AiOn/People/Solve Arm Poses")]
        public static void Menu() => Debug.Log("[AiOn] arm poses\n" + Build());

        /// <summary>Writes the mask and the pose clips (existing assets are updated in place, so their GUIDs hold).</summary>
        public static string Build()
        {
            var log = new StringBuilder();
            WriteMask();
            foreach (var pose in PersonClips.ArmPoses)
            {
                var muscles = Solve(pose, out var note);
                if (muscles == null) { log.AppendLine($"{pose}: {note}"); continue; }
                WriteClip(pose, muscles);
                log.AppendLine($"{pose}: {note}");
            }
            AssetDatabase.SaveAssets();
            return log.ToString();
        }

        public static AvatarMask Mask() => AssetDatabase.LoadAssetAtPath<AvatarMask>(MaskPath);
        public static AnimationClip Clip(string pose) => AssetDatabase.LoadAssetAtPath<AnimationClip>(PosePath(pose));

        static void WriteMask()
        {
            var m = Mask();
            bool make = !m;
            if (make) m = new AvatarMask();
            for (var p = AvatarMaskBodyPart.Root; p < AvatarMaskBodyPart.LastBodyPart; p++)
                m.SetHumanoidBodyPartActive(p, p == AvatarMaskBodyPart.LeftArm || p == AvatarMaskBodyPart.RightArm ||
                                                p == AvatarMaskBodyPart.LeftFingers || p == AvatarMaskBodyPart.RightFingers);
            m.transformCount = 0;
            if (make) AssetDatabase.CreateAsset(m, MaskPath); else EditorUtility.SetDirty(m);
        }

        /// <summary>Curve property name of a muscle in a Humanoid clip ("Left Index 1 Stretched" → "LeftHand.Index.1 Stretched").</summary>
        public static string CurveName(int muscle)
        {
            var n = HumanTrait.MuscleName[muscle];
            if (muscle < FirstFinger) return n;
            var side = n.StartsWith("Left ") ? "LeftHand" : "RightHand";
            var rest = n.Substring(n.IndexOf(' ') + 1); // "Index 1 Stretched" / "Index Spread"
            int sp = rest.IndexOf(' ');
            return side + "." + rest.Substring(0, sp) + "." + rest.Substring(sp + 1);
        }

        static void WriteClip(string pose, float[] muscles)
        {
            var path = PosePath(pose);
            var clip = Clip(pose);
            bool make = !clip;
            if (make) clip = new AnimationClip { name = "arms_" + pose };
            else clip.ClearCurves();
            for (int i = 0; i < ArmMuscles + Fingers; i++)
            {
                int m = i < ArmMuscles ? FirstArmMuscle + i : FirstFinger + (i - ArmMuscles);
                float v = muscles[m];
                clip.SetCurve("", typeof(Animator), CurveName(m), AnimationCurve.Constant(0f, 1f, v));
            }
            var st = AnimationUtility.GetAnimationClipSettings(clip);
            st.loopTime = true;
            AnimationUtility.SetAnimationClipSettings(clip, st);
            if (make) AssetDatabase.CreateAsset(clip, path); else EditorUtility.SetDirty(clip);
        }

        // ---------------------------------------------------------------- solving

        /// <summary>Finger muscles per pose (stretched: +1 straight, -1 curled): a grip on the bar, a relaxed hand, a flat hand.</summary>
        static float FingerValue(string pose, int muscle)
        {
            var n = HumanTrait.MuscleName[muscle];
            bool thumb = n.Contains("Thumb"), spread = n.Contains("Spread");
            if (spread) return pose == PersonClips.ArmsSitBack ? 0.25f : 0f;
            switch (pose)
            {
                case PersonClips.ArmsCart: return thumb ? (n.Contains(" 1 ") ? 0.2f : -0.3f) : -0.75f; // round the bar
                case PersonClips.ArmsSitKnees: return thumb ? 0.3f : 0.15f; // relaxed, a little curled over the knee
                default: return thumb ? 0.6f : 0.75f; // flat on the floor
            }
        }

        public static float[] Solve(string pose, out string note)
        {
            note = "";
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(PeopleBuilder.PrefabPath("jeongmin"));
            if (!prefab) { note = "no jeongmin prefab"; return null; }
            using var s = new RocketboxPreview.Stage(false);
            var go = (GameObject)Object.Instantiate(prefab);
            s.Add(go);
            go.transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
            var a = go.GetComponentInChildren<Animator>();
            if (!a || !a.isHuman || !a.runtimeAnimatorController) { note = "no humanoid animator"; return null; }
            a.cullingMode = AnimatorCullingMode.AlwaysAnimate;
            a.Rebind();
            if (a.layerCount > PersonClips.ArmsLayer) a.Play(PersonClips.ArmsNone, PersonClips.ArmsLayer, 0f);
            a.Play(pose == PersonClips.ArmsCart ? "idle" : "sit", 0, 0.3f);
            a.Update(0f); a.Update(0.001f);
            var gripR = PersonRig.Deep(go.transform, PersonRig.GripR);
            var gripL = PersonRig.Deep(go.transform, PersonRig.GripL);
            if (!gripR || !gripL) { note = "no grips"; return null; }

            var handler = new HumanPoseHandler(a.avatar, a.transform);
            var hp = new HumanPose();
            handler.GetHumanPose(ref hp);
            var start = (float[])hp.muscles.Clone();
            for (int m = FirstFinger; m < FirstFinger + Fingers; m++) hp.muscles[m] = FingerValue(pose, m);

            // targets (world = the person's root frame here: at the origin, facing +z)
            Vector3 tR, tL;
            float scale = a.transform.localScale.y / RocketboxCast.MaleScale;
            if (pose == PersonClips.ArmsCart)
            {
                var h = PersonProps.CartHandle * scale + Vector3.up * 0.03f; // the palm on top of the bar
                tR = h + Vector3.right * PersonProps.CartGripHalf * scale;
                tL = h + Vector3.left * PersonProps.CartGripHalf * scale;
            }
            else
            {
                Vector3 Bone(HumanBodyBones b) => a.GetBoneTransform(b).position;
                if (pose == PersonClips.ArmsSitKnees)
                {
                    tR = Vector3.Lerp(Bone(HumanBodyBones.RightUpperLeg), Bone(HumanBodyBones.RightLowerLeg), 0.75f) + Vector3.up * 0.085f;
                    tL = Vector3.Lerp(Bone(HumanBodyBones.LeftUpperLeg), Bone(HumanBodyBones.LeftLowerLeg), 0.75f) + Vector3.up * 0.085f;
                }
                else
                {
                    var hips = Bone(HumanBodyBones.Hips);
                    tR = new Vector3(hips.x + 0.20f, 0.018f, hips.z - 0.20f);
                    tL = new Vector3(hips.x - 0.20f, 0.018f, hips.z - 0.20f);
                }
            }

            float Cost()
            {
                handler.SetHumanPose(ref hp);
                float c = (gripR.position - tR).sqrMagnitude + (gripL.position - tL).sqrMagnitude;
                // palms down (the palm normal is -x of the right grip, +x of the left)
                float dR = Vector3.Dot(gripR.rotation * PersonRig.PalmNormal(true), Vector3.down);
                float dL = Vector3.Dot(gripL.rotation * PersonRig.PalmNormal(false), Vector3.down);
                c += 0.004f * ((1f - dR) + (1f - dL));
                // stay near the clip's own arms (no wild twists for the same reach)
                for (int i = 0; i < ArmMuscles; i++) { float d = hp.muscles[FirstArmMuscle + i] - start[FirstArmMuscle + i]; c += 0.0002f * d * d; }
                return c;
            }

            float best = Cost();
            for (float step = 0.25f; step > 0.004f; step *= 0.5f)
            {
                for (int pass = 0; pass < 12; pass++)
                {
                    bool moved = false;
                    for (int i = 0; i < ArmMuscles; i++)
                    {
                        int m = FirstArmMuscle + i;
                        foreach (var dir in new[] { 1f, -1f })
                        {
                            float was = hp.muscles[m];
                            hp.muscles[m] = Mathf.Clamp(was + dir * step, -1f, 1f);
                            float c = Cost();
                            if (c < best - 1e-7f) { best = c; moved = true; break; }
                            hp.muscles[m] = was;
                        }
                    }
                    if (!moved) break;
                }
            }
            Cost();
            float eR = (gripR.position - tR).magnitude, eL = (gripL.position - tL).magnitude;
            float pR = Vector3.Dot(gripR.rotation * PersonRig.PalmNormal(true), Vector3.down);
            float pL = Vector3.Dot(gripL.rotation * PersonRig.PalmNormal(false), Vector3.down);
            note = $"reach error R {eR * 100:0.0} cm, L {eL * 100:0.0} cm; palms down R {pR:0.00}, L {pL:0.00}";
            handler.Dispose();
            return hp.muscles;
        }
    }
}
