import * as st from './game/state.js';
import { packGrid, bagList } from './game/pack.js';
import { CATALOG } from './game/items.js';
import { writeFileSync } from 'node:fs';
const out = process.argv[2];
const seeds = [0, 1, 2, 3, 7, 42, 99, 12345, 2147483647, 4294967295, ...Array.from({ length: 200 }, (_, i) => i * 7919 + 13)];
const conditions = seeds.map(seed => ({ seed, cond: st.conditions(seed) }));
const mart = Object.fromEntries(Object.entries(CATALOG).filter(([, c]) => !c.notSold && !c.atmOnly).map(([id, c]) => [id, c.price]));
// Scenario: the same calls the C# parity test makes, in the same order.
const G = st.createGame({ seed: 11 });
const steps = [];
const snap = (label, extra = {}) => steps.push({ label, ...extra });
st.buy(G, { radio: 1, batteries_aa: 2, powerbank: 2, bars: 3 }, mart); snap('buy');
st.advance(G, 95); snap('advance95');
st.spendSlot(G, 'mart', 2);
st.pack(G, 'water_2l', 2); st.pack(G, 'bars', 3); st.pack(G, 'powerbank', 2); st.pack(G, 'meds', 1);
st.setPocket(G, 'powerbank', 2);
snap('packed', { bagLoad: st.bagLoad(G), bagCells: st.bagCells(G), pocketLoad: st.pocketLoad(G), layout: packGrid(bagList(G)) });
st.check(G, 'radio'); st.check(G, 'flashlight');
const drained = st.drainCharge(G, 'flashlight', 12.5);
st.trade(G, { ramen: 2 }, { batteries_old: 1 }, 'clerk');
st.consume(G, 'bars', 1, 'bag');
st.note(G, '  급수차 9시  ', 'official', 'centerNotice');
st.adjust(G, 'tension', 10);
st.advance(G, 600, { awake: false });
G.know.bagOn = true;
const speed = st.speedMul(G);
st.checkpoint(G, 'dday');
st.buy(G, { water_500: 3 }, mart);
st.advance(G, 30.4);
const clock = st.fmtClock(G);
const big = packGrid([{ id: 'gas_stove', n: 2 }, { id: 'water_2l', n: 3 }, { id: 'first_aid', n: 2 }, { id: 'radio', n: 2 }, { id: 'bars', n: 9, pocket: 9 }, { id: 'blackout_curtain', n: 1 }, { id: 'clothes', n: 1 }]);
writeFileSync(out, JSON.stringify({ conditions, scenario: { drained, speed, clock, steps, final: JSON.parse(st.save(G)) }, bigPack: big }, null, 1));
console.log('ok', conditions.length, 'seeds;', clock, 'speed', speed, 'drained', drained, 'big fits', big.fits, 'overflow', JSON.stringify(big.overflow));
